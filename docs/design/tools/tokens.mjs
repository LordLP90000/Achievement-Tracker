// Generates assets/css/tokens.css and assets/js/tokens.js from tokens.json and checks the WCAG contrast pairs
// listed in tokens.json ($extensions["ql.contrast"]) for both themes and their Increase Contrast variants.
// No dependencies. Usage (from the repository root): node docs/design/tools/tokens.mjs
// Exits with code 1 if a pair is below its threshold (text 4.5:1 and non-text UI 3:1; 7:1 and 4.5:1 with
// Increase Contrast).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));

const lookup = (path) => path.split('.').reduce((node, key) => node?.[key], tokens);

const resolve = (value) => {
  if (typeof value !== 'string') return value;
  const ref = /^\{([^}]+)\}$/.exec(value);
  if (!ref) return value;
  const target = lookup(ref[1]);
  if (!target || target.$value === undefined) throw new Error(`Unresolved token reference ${value}`);
  return resolve(target.$value);
};

/** Flattens a token group into [name, value] pairs, skipping $-prefixed metadata keys. */
const flatten = (group, prefix = []) =>
  Object.entries(group).flatMap(([key, node]) => {
    if (key.startsWith('$')) return [];
    if (node && typeof node === 'object' && '$value' in node) return [[[...prefix, key].join('-'), node.$value]];
    return node && typeof node === 'object' ? flatten(node, [...prefix, key]) : [];
  });

const themeVars = (theme) =>
  flatten(tokens.theme[theme]).map(([name, value]) => `  --${name}: ${resolve(value)};`);

const px = (n) => (typeof n === 'number' ? `${n}px` : n);
const TYPES = Object.entries(tokens.type).filter(([key]) => !key.startsWith('$'));
// Families stay CSS references so a frame's platform (data-platform) can swap the system font underneath.
const familyRef = (v) => {
  const ref = /^\{font\.family\.([^}]+)\}$/.exec(v.fontFamily);
  return ref ? `var(--font-${ref[1]})` : v.fontFamily;
};
const typeVars = TYPES.flatMap(([name, { $value: v }]) => [
  `  --type-${name}-size: ${px(v.fontSize)};`,
  `  --type-${name}-line: ${px(v.lineHeight)};`,
  `  --type-${name}-weight: ${v.fontWeight};`,
  `  --type-${name}-tracking: ${v.letterSpacing};`,
]);
const familyVars = TYPES.map(([name, { $value: v }]) => `  --type-${name}-family: ${familyRef(v)};`);
// Android: Roboto (the system font) with its default spacing; SF Pro's tracking only applies on iOS.
const androidTracking = TYPES.filter(([, { $value: v }]) => !v.textTransform && v.fontFamily === '{font.family.text}').map(
  ([name]) => `  --type-${name}-tracking: 0;`,
);

const motionVars = [
  ...flatten(tokens.motion.duration).map(([n, v]) => `  --duration-${n}: ${v};`),
  ...flatten(tokens.motion.easing).map(([n, v]) => `  --ease-${n}: cubic-bezier(${v.join(', ')});`),
];

const staticVars = [
  ...flatten(tokens.space).map(([n, v]) => `  --space-${n}: ${v};`),
  ...flatten(tokens.radius).map(([n, v]) => `  --radius-${n}: ${v};`),
  ...flatten(tokens.size).map(([n, v]) => `  --size-${n}: ${v};`),
  ...flatten(tokens.color.rank).map(([n, v]) => `  --rank-${n}: ${resolve(v)};`),
  ...flatten(tokens.font.family)
    .filter(([n]) => n !== 'text-android')
    .map(([n, v]) => `  --font-${n}: ${v};`),
  ...typeVars,
  ...motionVars,
];

const css = [
  '/* Generated by tools/tokens.mjs from tokens.json. Do not edit by hand: change tokens.json and run',
  '   `node docs/design/tools/tokens.mjs` from the repository root. */',
  ':root {',
  ...staticVars,
  '}',
  '',
  '/* Re-declared on every platform scope so the families follow that scope’s --font-text. */',
  ':root,',
  '[data-platform] {',
  ...familyVars,
  '}',
  '',
  '[data-platform="android"] {',
  `  --font-text: ${tokens.font.family['text-android'].$value};`,
  ...androidTracking,
  '}',
  '',
  ':root,',
  '[data-theme="light"] {',
  '  color-scheme: light;',
  ...themeVars('light'),
  '}',
  '',
  '[data-theme="dark"] {',
  '  color-scheme: dark;',
  ...themeVars('dark'),
  '}',
  '',
  '/* Increase Contrast (iOS) / high-contrast text (Android): set per frame by the review toolbar. */',
  '[data-theme="light"][data-contrast="more"] {',
  ...themeVars('light-contrast'),
  '}',
  '',
  '[data-theme="dark"][data-contrast="more"] {',
  ...themeVars('dark-contrast'),
  '}',
  '',
].join('\n');

writeFileSync(join(root, 'assets', 'css', 'tokens.css'), css);

// WCAG 2.2 relative luminance and contrast ratio.
const channel = (c) => {
  const s = c / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
};
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// Increase-contrast themes override some tokens of their base theme.
const BASE = { light: 'light', dark: 'dark', 'light-contrast': 'light', 'dark-contrast': 'dark' };
const themeToken = (theme, path) => {
  const [group, name] = path.split('.');
  const node = tokens.theme[theme][group]?.[name] ?? tokens.theme[BASE[theme]][group]?.[name];
  if (!node) throw new Error(`Unknown token ${theme}.${path}`);
  return resolve(node.$value);
};

const pairs = tokens.$extensions['ql.contrast'];
const THRESHOLDS = {
  light: [['text', 4.5], ['ui', 3]],
  dark: [['text', 4.5], ['ui', 3]],
  'light-contrast': [['text', 7], ['ui', 4.5]],
  'dark-contrast': [['text', 7], ['ui', 4.5]],
};
const results = [];
for (const [theme, kinds] of Object.entries(THRESHOLDS)) {
  for (const [kind, min] of kinds) {
    for (const [fg, bg] of pairs[kind]) {
      const ratio = contrast(themeToken(theme, fg), themeToken(theme, bg));
      results.push({ theme, kind, fg, bg, ratio: Math.round(ratio * 100) / 100, min, pass: ratio >= min });
    }
  }
}

// The same values for the browser (the design-system page reads them; works from file:// without fetch).
const resolvedTheme = (theme) => {
  const base = Object.fromEntries(flatten(tokens.theme[BASE[theme]]).map(([name, value]) => [name, resolve(value)]));
  return theme === BASE[theme] ? base : { ...base, ...Object.fromEntries(flatten(tokens.theme[theme]).map(([name, value]) => [name, resolve(value)])) };
};
const js = [
  '/* Generated by tools/tokens.mjs from tokens.json. Do not edit by hand. */',
  'window.QL = window.QL || {};',
  `QL.TOKENS = ${JSON.stringify(tokens)};`,
  `QL.THEMES = ${JSON.stringify(Object.fromEntries(Object.keys(BASE).map((t) => [t, resolvedTheme(t)])))};`,
  `QL.CONTRAST = ${JSON.stringify(results)};`,
  '',
].join('\n');
writeFileSync(join(root, 'assets', 'js', 'tokens.js'), js);

const failures = results.filter((r) => !r.pass).length;
const rows = results.map(
  (r) => `${r.pass ? 'pass' : 'FAIL'}  ${r.theme.padEnd(14)}  ${r.kind.padEnd(4)}  ${r.ratio.toFixed(2).padStart(5)}:1 (min ${r.min})  ${r.fg} on ${r.bg}`,
);
process.stdout.write(`${rows.join('\n')}\n\n${rows.length - failures}/${rows.length} pairs pass. tokens.css and tokens.js written.\n`);
if (failures > 0) process.exitCode = 1;
